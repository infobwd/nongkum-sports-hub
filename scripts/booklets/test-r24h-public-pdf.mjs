import assert from "node:assert/strict";
import fs from "node:fs";
import {createHash} from "node:crypto";
import {assembleR25E,parts,expectedPdfSha,expectedBytes} from "./r25e-pdf-bundle.mjs";
const read=p=>fs.readFileSync(new URL("../../"+p,import.meta.url));
const txt=p=>read(p).toString("utf8");
const data=JSON.parse(txt("data/booklet-versions.json"));
const book=data.documents[2];

// The previous 155-page source must stay untouched for rollback and old reference maps.
const archived=read("assets/souvenir-2569-v42i10-g2-155pages.pdf");
assert.equal(archived.byteLength,4067611);
assert.equal(createHash("sha256").update(archived).digest("hex"),
  "a2a9f47f8bf871403c3995e6b4ebd102802e600fc20c16198eb12ab73b12e89d");

const updated=assembleR25E();
assert.equal(updated.byteLength,expectedBytes);
assert.equal(updated.subarray(0,5).toString("latin1"),"%PDF-");
assert.equal(createHash("sha256").update(updated).digest("hex"),expectedPdfSha);
assert.equal(parts.length,7);
assert.equal(book.source_path,parts[0]);
assert.equal(book.pdf_revision_sha256,expectedPdfSha);
assert.equal(book.delivery.part_count,7);
assert.equal(book.delivery.reassembled_bytes,expectedBytes);
assert.equal(book.page_count,155);
assert.equal(book.viewer_route,"./booklet-drive-viewer.html");
assert.equal(book.access_mode,"same_origin_reader");
assert.equal(book.availability,"available");
assert.equal(book.document_status,"draft_review_not_approved");
assert.equal(book.approved_at,null);
assert.equal(data.audit_155.anchor_count,486);
assert.equal(data.audit_155.position_parity_against_baseline,null);
assert.equal(data.audit_155.publication_approved,false);
assert.equal(data.documents[0].source_path,"assets/souvenir-2569-v2.pdf");
assert.equal(data.documents[1].source_path,"assets/souvenir-committee-2569-v3.pdf");

const js=txt("js/booklet-unified-viewer.js");
const html=txt("booklet-drive-viewer.html");
const cat=txt("js/booklets.js");
const entry=txt("booklets.html");
assert.match(js,/const PDF_PARTS = Object\.freeze/);
assert.match(js,/PDF_BYTE_LENGTH = 4229122/);
assert.match(js,/fetchPublishedPdfBytes\(\)/);
assert.match(js,/atob\(encoded\)/);
assert.match(js,/verifyPdfBytes\(bytes\)/);
assert.match(js,/crypto\.subtle\.digest/);
assert.match(js,/loadPublishedPdf\(\)/);
assert.match(js,/setPage\(/);
assert.match(js,/touchstart/);
assert.match(js,/touchmove/);
assert.match(js,/touchend/);
assert.doesNotMatch(js,/requestAccessToken|initTokenClient|Bearer /);
assert.doesNotMatch(js,/localStorage|sessionStorage|indexedDB/);
assert.match(html,/16v6cgEk8NyjVqo7TX_Sxd3QvT2NF7aAS\/view/);
assert.match(html,/\.\/css\/pdf-viewer\.css/);
assert.match(html,/id="r25eHighlightNotice"/);
assert.match(html,/ดูเล่มฉบับก่อนปรับ/);
assert.match(html,/ฉบับตรวจร่าง/);
assert.match(cat,/doc\.delivery\?\.part_count===7/);
assert.match(cat,/doc\.source_path==="assets\/r25d3-155pages\/part-01\.b64"/);
assert.match(entry,/ทั้งสามฉบับเปิดอ่านได้ในเว็บ/);
assert.match(txt("js/booklet-comparison-model.js"),/ANCHOR_REMAP_PENDING/);
const v2=read("assets/souvenir-2569-v2.pdf");
const v3=read("assets/souvenir-committee-2569-v3.pdf");
assert.equal(createHash("sha256").update(v2).digest("hex"),data.documents[0].pdf_revision_sha256);
assert.equal(createHash("sha256").update(v3).digest("hex"),data.documents[1].pdf_revision_sha256);
console.log("R25-E PASS: archived 155-page PDF unchanged; new same-origin 7-part PDF exact SHA/bytes; V2/V3 unchanged; old highlights disabled, review gate kept");
