assert.equal(book.source_path,source);
assert.equal(book.pdf_revision_sha256,createHash("sha256").update(f).digest("hex"));
assert.equal(book.page_count,155);
assert.equal(book.viewer_route,"./booklet-drive-viewer.html");
assert.equal(book.access_mode,"same_origin_reader");
assert.equal(book.availability,"available");
assert.equal(book.document_status,"draft_review_not_approved");
assert.equal(book.approved_at,null);
assert.equal(data.audit_155.anchor_count,486);
assert.equal(data.audit_155.publication_approved,false);
assert.equal(data.documents[0].source_path,"assets/souvenir-2569-v2.pdf");
assert.equal(data.documents[1].source_path,"assets/souvenir-committee-2569-v3.pdf");
const js=txt("js/booklet-unified-viewer.js");
const html=txt("booklet-drive-viewer.html");
const cat=txt("js/booklets.js");
const entry=txt("booklets.html");
assert.match(js,/const PUBLIC_PDF_URL = "\.\/assets\/souvenir-2569-v42i10-g2-155pages\.pdf"/);
assert.match(js,/async function loadPublishedPdf\(\)/);
assert.match(js,/fetch\(PUBLIC_PDF_URL\+"\?v=r24h1"/);
assert.match(js,/await openBytes\(await response\.arrayBuffer\(\)\)/);
assert.match(js,/loadPublishedPdf\(\);\s*\}\)\(\);/);
assert.match(js,/crypto\.subtle\.digest/);
assert.match(js,/verifyPdfBytes\(bytes\)/);
assert.match(js,/setPage\(/);
assert.match(js,/touchstart/);
assert.match(js,/touchmove/);
assert.match(js,/touchend/);
assert.match(js,/r24g-selected/);
assert.doesNotMatch(js,/requestAccessToken|initTokenClient|Bearer /);
assert.doesNotMatch(js,/localStorage|sessionStorage|indexedDB/);
