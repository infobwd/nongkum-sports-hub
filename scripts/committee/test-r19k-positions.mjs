// R19-K — coordinate and regression tests for all 250 source-verified committee entries.
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {createHash} from "node:crypto";
import vm from "node:vm";
const read=p=>readFileSync(new URL("../../"+p,import.meta.url),"utf8");
const index=JSON.parse(read("data/committee-pdf-positions-v3.json"));
const roster=JSON.parse(read("data/committee-2569-draft-public-review.json"));
const pdf=readFileSync(new URL("../../assets/souvenir-committee-2569-v3.pdf",import.meta.url));
assert.equal(index.source_sha256,createHash("sha256").update(pdf).digest("hex"));
assert.equal(index.source_sha256,roster.editorial_correction.corrected_pdf_sha256);
assert.equal(roster.source_sha256,roster.editorial_correction.original_source_sha256);
assert.equal(index.roster_revision,roster.revision);
assert.equal(index.source_pdf_pages,64);
assert.equal(index.qa.total,250);
assert.equal(index.qa.matched,250);
assert.equal(index.qa.unresolved,0);
assert.equal(Object.keys(index.entries).length,roster.entries.length);
const script=read("js/committee-pdf-highlight.js");
const viewer=read("js/pdf-viewer.js");
const bridge=read("js/committee-pdf-preview.js");
const html=read("committee-pdf-viewer.html");
const parent=read("committee.html");
assert.match(viewer,/const EXPECTED_PAGES = 41/);
assert.match(viewer,/source_pdf_pages/); // document/map schema must both be guarded.
assert.match(viewer,/committeeCoordinateIndex/);
assert.match(viewer,/committee-pdf-positions-v3\.json/);
assert.doesNotMatch(viewer,/page\.getTextContent\(\)/,"no per-device text extraction for highlights");
assert.match(bridge,/url\.searchParams\.set\("entry", reference\.id\)/);
assert.match(bridge,/กำลังดู/);
assert.match(html,/pdfHighlightLayer/);
assert.match(html,/js\/pdf-viewer\.js\?v=r19k2/);
assert.match(parent,/committee-pdf-preview\.js\?v=r19k2/);
new vm.Script(script);
new vm.Script(viewer);
const world={window:{}};
new vm.Script(script).runInNewContext(world);
const api=world.window.NongkumCommitteeHighlight;
for (const e of roster.entries) {
  const selected={id:e.id,name:e.name,number:e.number||""};
  const rect=api.select(index,selected,e.pdf_page);
  assert.ok(rect,"verified map should cover "+e.id);
  assert.equal(rect.length,4);
  assert.ok(rect[0]>=0&&rect[0]<rect[2]&&rect[2]<=1);
  assert.ok(rect[1]>=0&&rect[1]<rect[3]&&rect[3]<=1);
}
const a=roster.entries.find(x=>x.id==="pdf-p11-l38");
const b=roster.entries.find(x=>x.id==="pdf-p11-l03");
assert.ok(a&&b&&a.name===b.name);
assert.equal(a.number,"14.2.4");
assert.equal(b.number,"12.4");
const ra=api.select(index,{id:a.id,name:a.name,number:a.number},11);
const rb=api.select(index,{id:b.id,name:b.name,number:b.number},11);
assert.ok(ra[1]>rb[1]+0.5,"same person different clauses must yield distinct physical rows");
assert.equal(api.select(index,{id:a.id,name:a.name,number:"12.4"},11),null);
assert.equal(api.select(index,{id:a.id,name:"คนอื่น",number:a.number},11),null);
assert.equal(api.select(index,{id:a.id,name:a.name,number:a.number},12),null);
assert.equal(api.select(index,{id:"pdf-p11-l99",name:a.name,number:a.number},11),null);
assert.equal(api.select({ ...index,source_sha256:"bad"},{id:a.id,name:a.name,number:a.number},11),null);
const marks=[];
const overlay={style:{},ownerDocument:{createElement:()=>({style:{},setAttribute(){}})},
  replaceChildren(){marks.length=0;},appendChild(element){marks.push(element);}};
const canvas={style:{width:"595px",height:"842px"}};
const chosen={id:a.id,name:a.name,number:a.number};
const mark=api.draw({index,target:chosen,page:11,viewport:{width:595,height:842},overlay,canvas});
assert.ok(mark&&marks.length===1);
assert.ok(mark.top>750,"clause 14.2.4 should be at the bottom of page 11");
assert.equal(marks[0].className,"committee-pdf-name-highlight");
const x=parseFloat(marks[0].style.left), y=parseFloat(marks[0].style.top);
canvas.style.width="1190px";canvas.style.height="1684px";
const zoom=api.draw({index,target:chosen,page:11,viewport:{width:1190,height:1684},overlay,canvas});
assert.ok(zoom&&marks.length===1);
assert.ok(Math.abs(parseFloat(marks[0].style.left)-2*x)<0.05);
assert.ok(Math.abs(parseFloat(marks[0].style.top)-2*y)<0.05);
assert.equal(api.draw({index,target:{...chosen,name:"ไม่ตรง"},page:11,viewport:{width:1190,height:1684},overlay,canvas}),null);
assert.equal(marks.length,0,"failed match must clear stale highlight");
console.log("R19-K PASS: 250/250 source coordinates, duplicate names, exact entry ID, zoom and safe fallback");
