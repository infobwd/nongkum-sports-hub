import assert from "node:assert/strict";
import fs from "node:fs";
import {createHash} from "node:crypto";
const read=p=>fs.readFileSync(new URL("../../"+p,import.meta.url));
const txt=p=>read(p).toString("utf8");
const data=JSON.parse(txt("data/booklet-versions.json"));
const book=data.documents[2];
const f=read("assets/souvenir-2569-v42i10-g2-155pages.pdf");
const source="assets/souvenir-2569-v42i10-g2-155pages.pdf";
assert.equal(f.byteLength,4067611,"exact 155-page source size");
assert.equal(f.subarray(0,5).toString("latin1"),"%PDF-");
