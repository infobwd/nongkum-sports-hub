def fragment(html: str, name: str, width:float, height:float):
    head=f'''<!DOCTYPE html><html lang="th"><meta charset="utf-8"><style>
    @page {{size:{width}pt {height}pt; margin:0}}
    html,body{{margin:0;padding:0;color:#183b55;font-family:'Noto Sans Thai','Waree',sans-serif}}
    *{{box-sizing:border-box}} .panel{{border:1pt solid {LINE};background:#f9fbfd;border-radius:5pt;padding:10pt 12pt;margin-bottom:7pt}}
    .subtitle{{font-size:10.2pt;color:#62798b;margin:0 0 12pt}}h2{{font-size:14pt;color:{NAVY};margin:0 0 9pt}}h3{{font-size:11pt;color:{NAVY};margin:0 0 4pt}}
    .gold{{background:#fff5e3;border-left:4pt solid {GOLD};padding:10pt 12pt}}
    .small{{font-size:9.4pt;color:#587186;line-height:1.5}}
    </style>'''
    path=OUT.parent/f'_fragment_{name}.pdf'
    HTML(string=head+html+'</html>',base_url=str(OUT.parent)).write_pdf(str(path))
    dd=fitz.open(path)
    if len(dd)!=1:raise RuntimeError(f'fragment {name} spilled to {len(dd)} pages')
    return dd


def wipe(p,rect):
    p.add_redact_annot(rect,fill=(1,1,1))
    p.apply_redactions(images=0,graphics=0,text=0)


def paste(p,rect,html,name):
    wipe(p,rect)
    with fragment(html,name,rect.width,rect.height) as doc:
        p.show_pdf_page(rect,doc,0,overlay=True)

