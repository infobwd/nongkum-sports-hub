// R16 actual 237-row draft, chronology, missing-time/date, deterministic pagination.
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
const source=readFileSync(new URL("../../js/schedule-order.js",import.meta.url),"utf8");
const ctx=vm.createContext({Intl,Date});
new vm.Script(source).runInContext(ctx);
const order=ctx.NongkumScheduleOrder;
const data=JSON.parse(readFileSync(new URL("../../data/program-from-pdf-2569-20261104-draft.json",import.meta.url),"utf8"));
const fixtures=data.fixtures;
assert.equal(fixtures.length,237);
const sorted=order.sortFixtures(fixtures);
assert.equal(sorted.length,237);
assert.equal(new Set(sorted.map(m=>m.id)).size,237);
assert.deepEqual(new Set(sorted.map(m=>m.id)),new Set(fixtures.map(m=>m.id)));
assert.ok(sorted.every((m,i)=>!i||order.compare(sorted[i-1],m)<=0),"chronological and deterministic");
assert.equal(sorted[0].planning_date,"2026-11-12","confirmed early matches first");
assert.equal(sorted[0].source_pdf.source_time,"09:00");
assert.equal(order.dayKey(sorted.at(-1)),null,"unconfirmed PDF year placed at end");
assert.equal(sorted.filter(m=>order.dayKey(m)===null).length,3,"keep three 2568 anomalies out of 2569");
assert.ok(sorted.slice(-3).every(m=>m.source_pdf.source_date_text==="17 พ.ย. 68"));
const athletics=sorted.filter(m=>m.kind==="track_event");
assert.equal(athletics.length,50);
assert.ok(athletics.every(m=>order.dayKey(m)==="2026-11-16"&&order.minutes(m)===null));
const first16=sorted.findIndex(m=>order.dayKey(m)==="2026-11-16");
const end16=sorted.findIndex(m=>order.dayKey(m)==="2026-11-17");
assert.ok(sorted.slice(first16,end16).filter(m=>order.minutes(m)!==null).every(m=>sorted.indexOf(m)<sorted.indexOf(athletics[0])),"unknown times last within same day");
for(const limit of [12,24,48,237]){
  const groups=order.groupVisible(sorted.slice(0,limit));
  assert.deepEqual(groups.flatMap(g=>g.fixtures.map(m=>m.id)),sorted.slice(0,limit).map(m=>m.id),"load more never scrambles order");
}
assert.equal(order.dayKey({source_pdf:{source_date_iso:"2026-02-30"}}),null);
assert.equal(order.minutes({time:"25:00"}),null);
assert.equal(order.minutes({time:"8:30"}),510);
assert.equal(order.dayKey({source_pdf:{source_date_iso:"2025-11-17",source_date_text:"17 พ.ย. 68"}}),null);
assert.equal(order.dayKey({planning_date:"2026-11-12",planning_date_confirmation:"confirmed",source_pdf:{source_date_text:"17 พ.ย. 68"}}),"2026-11-12","approved effective date overrides ambiguous PDF");
assert.match(order.dayLabel("2026-11-18"),/18 พฤศจิกายน 2569/);
assert.equal(order.dayLabel(null),"รอยืนยันวันและเวลา");
const page=readFileSync(new URL("../../index.html",import.meta.url),"utf8");
const results=readFileSync(new URL("../../results.html",import.meta.url),"utf8");
const program=readFileSync(new URL("../../js/program.js",import.meta.url),"utf8");
const clearance=readFileSync(new URL("../../css/mobile-nav-clearance.css",import.meta.url),"utf8");
assert.match(page,/js\/schedule-order\.js/);
assert.match(program,/sortFixtures/);
assert.match(program,/groupVisible/);
assert.match(page,/เรียงตามวันที่และเวลา/);
for(const html of [page,results])assert.match(html,/mobile-nav-clearance\.css/);
assert.match(clearance,/--safe-bottom/);
assert.match(clearance,/body\[data-view="program"\] > main/);
assert.match(clearance,/body\[data-view="results"\] > main/);
assert.match(program,/pdf-viewer\.html\?page=/);
assert.match(program,/shareLatestCandidate/);
assert.equal(JSON.parse(readFileSync(new URL("../../data/public-results.json",import.meta.url),"utf8")).results.length,0);
console.log("R16 PASS: 237 chronological entries, draft year safeguards, stable 12-row load-more, shared mobile safe-area clearance");
